class Arithmetic
{
    public int iNo = 0;

    /////////////////////////////////////////////////////////////////////////////////////////
    //
    //  Function :     Arithmetic
    //  Description :  Parameterized Constructor
    //  Input :        Integer
    //  Output :       Nothing
    //  Author :       Shreya Pramod Pasalkar
    //
    /////////////////////////////////////////////////////////////////////////////////////////
    public Arithmetic(int A) 
    {
        this.iNo = A;
    }

    /////////////////////////////////////////////////////////////////////////////////////////
    //
    //  Function :     CheckEven
    //  Description :  It is used to return remainder
    //  Input :        Nothing
    //  Output :       Integer
    //  Author :       Shreya Pramod Pasalkar
    //
    /////////////////////////////////////////////////////////////////////////////////////////
    public int CheckEven()
    {
        int iRem = 0;

        iRem = this.iNo % 2;

        return iRem;
    }
}

