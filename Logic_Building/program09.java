class Arithmetic
{
    public int iNo = 0;

    /////////////////////////////////////////////////////////////////////////////////////////
    //
    //  Function :     Arithmetic
    //  Description :  Parameterized Constructor
    //  Input :        Integer
    //  Output :       Nothing
    //  Author :       Shreya Pramod Pasalkar
    //
    /////////////////////////////////////////////////////////////////////////////////////////
    public Arithmetic(int A) 
    {
        this.iNo = A;
    }

    /////////////////////////////////////////////////////////////////////////////////////////
    //
    //  Function :     CheckEven
    //  Description :  It is used to display is the given number is even or not 
    //  Input :        Nothing
    //  Output :       Nothing
    //  Author :       Shreya Pramod Pasalkar
    //
    /////////////////////////////////////////////////////////////////////////////////////////
    public void CheckEven()
    {
        if((this.iNo % 2) == 0)
        {
            System.out.println(iNo+" is Even number");
        }
        else
        {
            System.out.println(iNo+" is not a Even number");
        }
    }
}

