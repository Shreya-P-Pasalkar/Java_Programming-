class Arithmetic
{
    public int No1 = 0;
    public int No2 = 0;

    /////////////////////////////////////////////////////////////////////////////////////////
    //
    //  Function :     Arithmetic
    //  Description :  Parameterized Constructor
    //  Input :        integer, integer
    //  Output :       Nothing
    //  Author :       Shreya Pramod Pasalkar
    //
    /////////////////////////////////////////////////////////////////////////////////////////
    public Arithmetic(int A, int B) 
    {
        this.No1 = A;
        this.No2  = B;
    }

    /////////////////////////////////////////////////////////////////////////////////////////
    //
    //  Function :     Addition
    //  Description :  It is used to do addition of 2 numbers
    //  Input :        integer, integer
    //  Output :       integer
    //  Author :       Shreya Pramod Pasalkar
    //
    /////////////////////////////////////////////////////////////////////////////////////////
    public int Addition()
    {
        int iSum = 0;

        iSum = this.No1 + this.No2;

        return iSum;
    }
}

